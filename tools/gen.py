#!/usr/bin/env python3
"""Generate src/gen/gen_syms.c and src/gen/jni_slots.inc.

usage: gen.py <libSpyMouse.so> <vitagl_syms.txt>   (run from the project root; needs arm-vita-eabi-readelf on PATH)

gen_syms.c binds every undefined symbol of the .so that imports.c does not already provide:
  gl* with a w_gl* wrapper in glwrap.c -> the wrapper (softfp float arguments)
  gl* that vitaGL exports               -> vitaGL
  everything else                       -> a logging stub (returns 0), so a missing import shows up in log.txt, not as a crash
"""
import os, re, subprocess, sys

so, vglfile = sys.argv[1], sys.argv[2]
out = subprocess.check_output(["arm-vita-eabi-readelf", "--dyn-syms", "-W", so], text=True)
und = sorted({l.split()[7].split("@")[0] for l in out.splitlines() if " UND " in l and len(l.split()) >= 8})
vgl = set(open(vglfile).read().split())
imp = set(re.findall(r'^\s*\{\s*"([^"]+)"', open("src/imports.c").read() + open("src/imports.c").read(), re.M))
# entries sharing a line: { "a", ... }, { "b", ... }
imp |= set(re.findall(r'\{\s*"([A-Za-z_0-9]+)"\s*,', open("src/imports.c").read()))
wrap = set(re.findall(r'\b(w_gl\w+)\s*\(', open("src/glwrap.c").read()))

lines = ['/* generated by tools/gen.py - do not edit */', '#include "../sm.h"', '']
entries, decls = [], []
for n in und:
    if n in imp:
        continue
    if n.startswith("gl") and ("w_" + n) in wrap:
        decls.append("extern void w_%s();" % n); entries.append((n, "w_" + n))
    elif n.startswith("gl") and n in vgl:
        decls.append("extern void %s();" % n); entries.append((n, n))
    else:
        decls.append('static int stub_%s(void) { sm_unimpl("%s"); return 0; }' % (n, n)); entries.append((n, "stub_" + n))
lines += decls + ["", "const ImpSym gen_syms[] = {"]
lines += ['    { "%s", (void *)%s },' % e for e in entries] + ["    { NULL, NULL }", "};"]
os.makedirs("src/gen", exist_ok=True)
open("src/gen/gen_syms.c", "w").write("\n".join(lines) + "\n")
stubs = [e for e in entries if e[1].startswith("stub_")]
print("imports: %d undefined, %d from imports.c, %d GL/vitaGL, %d stubs" % (len(und), len([n for n in und if n in imp]), len(entries) - len(stubs), len(stubs)))
for n, _ in stubs:
    print("  stub:", n)

# 233 JNIEnv function slots, each a logging stub that names its index
with open("src/gen/jni_slots.inc", "w") as f:
    f.write("/* generated by tools/gen.py */\n")
    for i in range(233):
        f.write('static intptr_t jslot_%d(void) { sm_log("JNI: unimplemented slot %d\\n"); return 0; }\n' % (i, i))
    f.write("static void *const jslots[233] = {\n")
    f.write(",\n".join("    (void *)jslot_%d" % i for i in range(233)))
    f.write("\n};\n")
